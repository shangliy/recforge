#!/usr/bin/env python3
"""Write CHANGELOG.md: every audit.csv cell changed between committed versions and the released file.

    python3 changelog.py > CHANGELOG.md

The evidence files were written when a row was first coded; this log is how a cell in audit.csv that differs from
its evidence file can be traced to the commit (and the README or reconciliation entry) that changed it.
"""
import csv
import io
import subprocess
import sys
from pathlib import Path
from datetime import date

HERE = Path(__file__).resolve().parent
REL = "./audit.csv"  # relative to HERE, so the script does not depend on where the repository keeps it


def git(*args):
    try:
        return subprocess.run(["git", *args], cwd=HERE, capture_output=True, text=True, check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        sys.exit("changelog.py needs the git history of the data repository; outside it, read the released CHANGELOG.md")


def rows(text):
    return {r["key"]: r for r in csv.DictReader(io.StringIO(text))}


commits = git("log", "--reverse", "--format=%h %ad %s", "--date=short", "--", "audit.csv").splitlines()
versions = [(c.split()[0], c.split(" ", 2)[1], c.split(" ", 2)[2], rows(git("show", f"{c.split()[0]}:{REL}")))
            for c in commits]
versions.append(("this release", date.today().isoformat(), "changes since the last commit, in this submitted version", rows((HERE / "audit.csv").read_text())))

print("# audit.csv cell-level changelog\n")
print("Generated by `changelog.py` from the git history. `audit.csv` is authoritative; where an evidence file disagrees,")
print("the change is listed here with the commit that made it. Rows that first appear in a version are listed as added.\n")
print("The `ab_*` columns are new in this release, so changes to them before release are not listed as cell changes; their")
print("adjudications (PILOT correction, DMRL and AgentX duration) are recorded in `evidence-online-gates.md`.\n")
print("The reason for a recode is in the system's section of the evidence files or in `second-coder/reconciliation.md`;")
print("for example, AgentLTV C3 `NS` -> `N` applies the codebook rule that a loop selecting on its reported test data (C2 `test`)")
print("does not use test data once (see `evidence-part2.md`).\n")
for (_, _, _, old), (h, date, subject, new) in zip(versions, versions[1:]):
    lines = []
    for key, r in new.items():
        if key not in old:
            lines.append(f"- added `{key}` ({r['system']})")
            continue
        for col, v in r.items():
            before = old[key].get(col)
            if before is None:
                continue
            if before != v:
                lines.append(f"- `{key}` ({r['system']}) {col}: `{before}` → `{v}`")
    added_cols = [c for c in next(iter(new.values())) if c not in next(iter(old.values()))]
    if added_cols:
        lines.insert(0, "- new columns: " + ", ".join(f"`{c}`" for c in added_cols))
    lines += [f"- removed `{k}`" for k in old if k not in new]
    print(f"## {h} {date} {subject}\n")
    print("\n".join(lines) if lines else "- no cell changes")
    print()
